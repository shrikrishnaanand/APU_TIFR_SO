#!/bin/bash
#SBATCH --gres=gpu:1
#SBATCH --partition=gpu
#SBATCH --time=24:00:00
#SBATCH --mem=32G
#SBATCH --job-name=et_e0_5
#SBATCH --output=et_e0_5_%j.out
#SBATCH --error=et_e0_5_%j.out

# Usage (from inside et_e0/):  sbatch submit_et_e0_5.sh
# The notebook uses relative paths (NLO_e0/, NNLO_e0/, ../x_e_files/),
# so everything runs from the et_e0 directory.

cd "${SLURM_SUBMIT_DIR:-$(dirname "$0")}"
echo "== workdir: $(pwd)"

# Sage env created with micromamba (conda-forge sage + nbconvert):
#   export MAMBA_ROOT_PREFIX=/bhome/$USER/micromamba
#   /bhome/$USER/bin/micromamba create -y -n sage -c conda-forge sage nbconvert python=3.12
# No uenv/conda activate needed: just put the env's bin first on PATH.
SAGE_ENV=/bhome/$USER/micromamba/envs/sage
[ -x "$SAGE_ENV/bin/python" ] || { echo "!! $SAGE_ENV not found"; exit 1; }
export PATH=$SAGE_ENV/bin:$PATH

echo "== python:  $(which python)  ($(python --version 2>&1))"

# From here on, stop at the first real error
set -eo pipefail

# Fail early with a clear message if the env is missing packages
python -c "import nbconvert, sage.all" || {
  echo "!! nbconvert / sage not importable from $SAGE_ENV."
  echo "!! On a login node run: MAMBA_ROOT_PREFIX=/bhome/\$USER/micromamba /bhome/\$USER/bin/micromamba install -y -n sage -c conda-forge sage nbconvert"
  exit 1
}

NB=et_e0_5.ipynb
BASE=${NB%.ipynb}
mkdir -p NNLO_e0

echo "== 1) nbconvert $NB -> $BASE.sage"
python -m nbconvert --to script "$NB" --stdout > "$BASE.sage"

echo "== 2) preparse $BASE.sage -> $BASE.sage.py"
python - "$BASE.sage" <<'EOF'
import sys
from sage.repl.preparse import preparse_file
src = sys.argv[1]
with open(src) as f:
    code = preparse_file(f.read())
with open(src + ".py", "w") as f:
    # Same header `sage --preparse` uses, plus `x`, which the interactive
    # Sage/Jupyter session predefines but a plain script does not.
    f.write("# Autogenerated from %s\n"
            "from sage.all_cmdline import *\n"
            "x = SR.var('x')\n\n" % src)
    f.write(code)
EOF

echo "== 3) running $BASE.sage.py"
export PYTHONUNBUFFERED=1
python "$BASE.sage.py"
echo "== done"
